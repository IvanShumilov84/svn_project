		/// <summary>
		/// Calculates a GraphicsPath that fits the given shape inside the given Rectangle
		/// </summary>
		/// <param name="Rect">Rectangle in which to calculate path</param>
		/// <param name="Shape">Shape of path to calculate</param>
		/// <returns>Calculated GraphicsPath</returns>
		protected GraphicsPath CalculateShapePath(Rectangle Rect, Shapes Shape)
		{
			GraphicsPath		path		= new GraphicsPath() ;
            try
            {
                if (Shape == Shapes.Ellipse)
                {
                    path.AddEllipse(Rect);
                }
                else
                {
                    int d = 2 * cornerRadius;

                    if (d > (Rect.Width / 2))
                    {
                        d = Rect.Width / 2;
                    }
                    if (d > (Rect.Height / 2))
                    {
                        d = Rect.Height / 2;
                    }

                    if (d < 1)
                    {
                        //too small to make a rounded rect - use the whole rect
                        path.AddRectangle(Rect);
                        // Caller is reponsible to dispose the path
                        return path;
                    }

                    path.AddArc(Rect.Left, Rect.Top, d, d, 180, 90);
                    path.AddLine(Rect.Left + cornerRadius, Rect.Top, Rect.Right - cornerRadius, Rect.Top);

                    path.AddArc(Rect.Right - d, Rect.Top, d, d, 270, 90);
                    path.AddLine(Rect.Right, Rect.Top + cornerRadius, Rect.Right, Rect.Bottom - cornerRadius);

                    path.AddArc(Rect.Right - d, Rect.Bottom - d, d, d, 0, 90);
                    path.AddLine(Rect.Right - cornerRadius, Rect.Bottom, Rect.Left + cornerRadius, Rect.Bottom);

                    path.AddArc(Rect.Left, Rect.Bottom - d, d, d, 90, 90);
                    path.AddLine(Rect.Left, Rect.Bottom - cornerRadius, Rect.Left, Rect.Top + cornerRadius);
                }
            }
            catch (Exception)
            {
                path.Dispose();
            }
            // Caller is reponsible to dispose the path
			return path ;
		}

