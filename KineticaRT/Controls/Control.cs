			if( disposing )
			{
                ObjectSearch = null;
                PropertyChanged = null;
				//remove from event pool
                lock (queueLock)
				{
					if (inQueue)
					{
						pool.UpdateEvent -= hdlr ;
					}
				}
                
                foreColorBrush.Dispose();
                backColorBrush.Dispose() ;
                toolTip.Dispose();
                toolTipErrorProvider.Dispose();
                //errorProviderManager.Dispose(this);

				if(components != null)
				{
					components.Dispose();
				}
			}
            lock (this)
            {
                base.Dispose(disposing);
            }
		}
