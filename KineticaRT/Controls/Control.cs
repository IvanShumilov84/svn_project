					Color		light ;
					Color		dark ;
                    Color       top_brush_color;
                    Color       bottom_brush_color;

					dark = ControlPaint.Dark(BaseColor) ;
					light = ControlPaint.Light(BaseColor) ;

                    if (Look == BorderType.Raised)
					{
                        top_brush_color = light;
                        bottom_brush_color = dark;
					}
					else
					{
                        top_brush_color = dark;
                        bottom_brush_color = light;
					}

                    using (Brush top_brush = new SolidBrush(top_brush_color),
                        bottom_brush = new SolidBrush(bottom_brush_color))
                    {
                        //draw raising
                        temp_rect.Height = 2;
                        g.FillRectangle(top_brush, temp_rect);

                        temp_rect.Y = Rect.Bottom - 2;
                        g.FillRectangle(bottom_brush, temp_rect);

                        temp_rect = Rect;
                        temp_rect.Width = 2;
                        g.FillRectangle(top_brush, temp_rect);

                        temp_rect.X = Rect.Right - 2;
                        g.FillRectangle(bottom_brush, temp_rect);

                        //...and corner pixels
                        g.FillRectangle(top_brush, Rect.Right - 2, Rect.Top, 1, 1);
                        g.FillRectangle(bottom_brush, Rect.Left + 1, Rect.Bottom - 1, 1, 1);
                    }
				}
				break ;

            case BorderType.EditBox:
				{
					Point[]			corners		= new Point[4] ;

					//left and top are dark
                    using (Pen left_pen = new Pen(Color.FromKnownColor(KnownColor.ControlDark), 1),
                        in_left_pen = new Pen(Color.Black, 1),
                        right_pen = new Pen(Color.White, 1),
                        in_right_pen = new Pen(Color.FromKnownColor(KnownColor.ControlLight), 1))
                    {

                        corners[0].X = Rect.Left;
                        corners[1].X = Rect.Left;
                        corners[2].X = Rect.Right - 1;
                        corners[3].X = Rect.Right - 1;

                        corners[0].Y = Rect.Bottom - 1;
                        corners[1].Y = Rect.Top;
                        corners[2].Y = Rect.Top;
                        corners[3].Y = Rect.Bottom - 1;

                        //draw a line left and top
                        g.DrawLine(left_pen, corners[0], corners[1]);
                        corners[1].X++;
                        g.DrawLine(left_pen, corners[1], corners[2]);

                        //draw a line right and bottom
                        corners[2].Y++;
                        g.DrawLine(right_pen, corners[2], corners[3]);
                        corners[3].X--;
                        g.DrawLine(right_pen, corners[3], corners[0]);

                        //then inside that
                        corners[0].X++;
                        corners[0].Y--;
                        //corners[1].X ++ ;
                        corners[1].Y++;
                        corners[2].X--;
                        //corners[2].Y ++ ;
                        //corners[3].X -- ;
                        corners[3].Y--;

                        g.DrawLine(in_left_pen, corners[0], corners[1]);
                        corners[1].X++;
                        g.DrawLine(in_left_pen, corners[1], corners[2]);

                        corners[2].Y++;
                        g.DrawLine(in_right_pen, corners[2], corners[3]);
                        corners[3].X--;
                        g.DrawLine(in_right_pen, corners[3], corners[0]);
                    }
				}
				break ;

            case BorderType.Flat:
				{
					if (Pixels == 0)				return ;

					Rectangle       rect ;

                    using (Brush brush = new SolidBrush(BaseColor))
                    {
                        rect = Rect;
                        rect.Width = Pixels;
                        g.FillRectangle(brush, rect);

                        rect.X = Rect.Right - Pixels;
                        g.FillRectangle(brush, rect);

                        rect.X = Rect.X + Pixels;
                        rect.Width = Rect.Width - 2 * Pixels;
                        rect.Height = Pixels;
                        g.FillRectangle(brush, rect);

                        rect.Y = Rect.Bottom - Pixels;
                        g.FillRectangle(brush, rect);
                    }
				}
				break ;

            case BorderType.Shaded:
            case BorderType.ShadedWithInset:
				{
					Color			light ;
					Color			dark ;
					Region			old_rgn ;
					Rectangle		inner_rect		= Rect ;

					inner_rect.Inflate(-Pixels, -Pixels) ;

					dark	= ControlPaint.Dark(BaseColor, 0.15f) ;
					light	= ControlPaint.Light(BaseColor, 0.8f) ;

                    using (Brush brush = new LinearGradientBrush(Rect, light, dark, 45, false))
                    {
                        using (Region rgn = new Region(inner_rect))
                        {
                            old_rgn = g.Clip;
                            g.ExcludeClip(rgn);

                            g.FillRectangle(brush, Rect);

                            g.Clip = old_rgn;
                        }
                    }

                    if (Look == BorderType.ShadedWithInset)
					{
                        DrawSquareBorder(g, inner_rect, BorderType.Indented, BaseColor, 2);
					}
				}
				break ;

            case BorderType.Rounded:
            case BorderType.RoundedWithInset:
				{
					Color				outside ;
					Rectangle			inner_rect		= Rect ;
					Point[]				point			= new Point[4] ;
					Point				temp_point		= new Point() ;

					inner_rect.Inflate(-Pixels, -Pixels) ;

					//top & left...
					outside = ControlPaint.Light(BaseColor, (float)0.8) ;

					//top
					point[0] = new Point(Rect.Left, Rect.Top) ;
					point[1] = new Point(inner_rect.Left, inner_rect.Top) ;
					point[2] = new Point(inner_rect.Right, inner_rect.Top) ;
					point[3] = new Point(Rect.Right, Rect.Top) ;
					temp_point.X = inner_rect.Left ;
					temp_point.Y = Rect.Top ;
                    using (Brush brush = new LinearGradientBrush(temp_point, point[1], outside, BaseColor))
                    {
                        g.FillPolygon(brush, point);
                    }

					//left
					point[2].X = inner_rect.Left ;
					point[2].Y = inner_rect.Bottom ;
					point[3].X = Rect.Left ;
					point[3].Y = Rect.Bottom ;
					temp_point.X = Rect.Left ;
					temp_point.Y = inner_rect.Top ;
                    using (Brush brush = new LinearGradientBrush(temp_point, point[1], outside, BaseColor))
                    {
                        g.FillPolygon(brush, point);
                    }

					//right & bottom...
					outside = ControlPaint.Dark(BaseColor, (float)0.15) ;

					//right
					point[0].X = Rect.Right ;
					point[0].Y = Rect.Bottom ;
					point[1].X = inner_rect.Right ;
					point[1].Y = inner_rect.Bottom ;
					point[2].X = inner_rect.Right ;
					point[2].Y = inner_rect.Top ;
					point[3].X = Rect.Right ;
					point[3].Y = Rect.Top ;
					temp_point.X = inner_rect.Right - 1 ;
					temp_point.Y = Rect.Bottom ;
                    using (Brush brush = new LinearGradientBrush(point[0], temp_point, outside, BaseColor))
                    {
                        g.FillPolygon(brush, point);
                    }

					//bottom
					point[2].X = inner_rect.Left ;
					point[2].Y = inner_rect.Bottom ;
					point[3].X = Rect.Left ;
					point[3].Y = Rect.Bottom ;
					temp_point.X = Rect.Right ;
					temp_point.Y = inner_rect.Bottom - 1 ;
                    using (Brush brush = new LinearGradientBrush(point[0], temp_point, outside, BaseColor))
                    {
                        g.FillPolygon(brush, point);
                    }

                    if (Look == BorderType.RoundedWithInset)
					{
                        DrawSquareBorder(g, inner_rect, BorderType.Indented, BaseColor, 2);
					}
				}
				break ;
			}
		}

		/// <summary>
        /// Draws the specified Type Border in the specified Shape
		/// </summary>
		/// <param name="g">Graphics object with which to draw</param>
		/// <param name="Rect">Rectangle inside which to draw</param>
        /// <param name="Look">Border Type to give the Shape</param>
		/// <param name="BaseColor">Base Color to shade</param>
		/// <param name="Shape">Shape to draw. Does nothing if 'Rectangle' is specified</param>
        /// <param name="Pixels">Width of border in pixels (variable width Types only)</param>
        protected void DrawShapedBorder(Graphics g, Rectangle Rect, BorderType Look, Color BaseColor, Shapes Shape, int Pixels)
		{
			if (Shape == Shapes.Rectangle)			return ;

			switch (Look)
			{
                case BorderType.None:
				{
					//no drawing to do
				}
				break ;

            case BorderType.Raised:
            case BorderType.Indented:
            case BorderType.EditBox:
            case BorderType.Shaded:
            case BorderType.ShadedWithInset:
            case BorderType.Rounded:
            case BorderType.RoundedWithInset:
				{
					Color			light ;
					Color			dark ;
					bool			indent ;
					Brush			brush ;
					Region			old_rgn ;
					Rectangle		inner_rect		= Rect ;
					int				width ;

                    if (Look == BorderType.Indented || Look == BorderType.EditBox)
					{
						indent = true ;
					}
					else
					{
						indent = false ;
					}

                    if (Look == BorderType.Shaded || Look == BorderType.ShadedWithInset ||
                        Look == BorderType.Rounded || Look == BorderType.RoundedWithInset)
					{
						width = Pixels ;
					}
					else
					{
						width = 2 ;
					}

					inner_rect.Inflate(-width, -width) ;

					dark	= ControlPaint.Dark(BaseColor, 0.15f) ;
					light	= ControlPaint.Light(BaseColor, 0.8f) ;

					if (Rect.Width <= 0 || Rect.Height <= 0)
					{
						brush = new SolidBrush(BaseColor) ;
					}
					else if (indent)
					{
						brush = new LinearGradientBrush(Rect, dark, light, 45, false) ;
					}
					else
					{
						brush = new LinearGradientBrush(Rect, light, dark, 45, false) ;
					}
                    using (brush)
                    {
                        using (GraphicsPath path = CalculateShapePath(inner_rect, Shape))
                        {
                            using (Region rgn = new Region(path))
                            {
                                old_rgn = g.Clip;
                                g.ExcludeClip(rgn);

                                g.FillRectangle(brush, Rect);

                                if (Look == BorderType.ShadedWithInset || Look == BorderType.RoundedWithInset)
                                {
                                    g.Clip = rgn;
                                    DrawShapedBorder(g, inner_rect, BorderType.Indented, BaseColor, Shape, 2);
                                }

                                g.Clip = old_rgn;
                            }
                        }
                    }
				}
				break ;

            case BorderType.Flat:
				{
					Region			old_rgn ;
					Rectangle		inner_rect		= Rect ;

					inner_rect.Inflate(-Pixels, -Pixels) ;

                    using (Brush brush = new SolidBrush(BaseColor))
                    {
                        using (GraphicsPath path = CalculateShapePath(inner_rect, Shape))
                        {
                            using (Region rgn = new Region(path))
                            {
                                old_rgn = g.Clip;
                                g.ExcludeClip(rgn);

                                g.FillRectangle(brush, Rect);

                                g.Clip = old_rgn;
                            }
                        }
                    }
				}
				break ;
			}
		}

