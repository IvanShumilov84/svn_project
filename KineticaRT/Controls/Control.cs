		/// <summary>
		/// Recalculates the DisplayRectangle based on the current ClientRectangle
		/// and Appearance.
		/// </summary>
		protected virtual void CalculateDisplayRectangle()
		{
			switch (borderType)
			{
				case BorderType.None:
				{
					displayRect = ClientRectangle ;
				}
				break ;

				case BorderType.Raised:
				case BorderType.Indented:
				case BorderType.EditBox:
				{
					displayRect = ClientRectangle ;
					displayRect.Inflate(-2, -2) ;
				}
				break ;

				case BorderType.Flat:
				case BorderType.Shaded:
				case BorderType.Rounded:
				{
					int			width		= BorderWidthPixels(ClientRectangle) ;

					displayRect = ClientRectangle ;
					displayRect.Inflate(-width, -width) ;
				}
				break ;

				case BorderType.ShadedWithInset:
				case BorderType.RoundedWithInset:
				{
					int			width		= BorderWidthPixels(ClientRectangle) ;

					displayRect = ClientRectangle ;
					displayRect.Inflate(-width-2, -width-2) ;
				}
				break ;
			}
		}

		/// <summary>
		/// Converts BorderWidth property to a number of pixels in the given rectangle
        /// Ignores current border Type
		/// </summary>
		/// <param name="Rect">Rectangle in which border will be</param>
		/// <returns>Width in Pixels of border</returns>
		protected int BorderWidthPixels(Rectangle Rect)
		{
			int		width		= 0 ;

			if (borderWidth > 0.5)			//number of pixels
			{
				width = (int)BorderWidth ;
			}
			else if (borderWidth > 0)		//proportion
			{
				// '+1' is to ensure rounding upwards
				int		x_width		= (int)((Rect.Width + 1) * borderWidth) ;
				int		y_width		= (int)((Rect.Height + 1) * borderWidth) ;

				//border width is min of x and y widths...
				width = Math.Min(x_width, y_width) ;

				//...but always >= 1 pixel
				if (width < 1)
				{
					width = 1 ;
				}
			}

			return width ;
		}

