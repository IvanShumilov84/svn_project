        private void ReadStore()
        {
            try
            {
                System.Collections.Generic.Queue<PointF> data = new System.Collections.Generic.Queue<PointF>(100);

                System.Xml.XmlReader xmlReader;
                string filename = System.IO.Path.ChangeExtension(fileName, "xml");
                System.IO.Stream stream ;
                stream = new System.IO.FileStream(filename, System.IO.FileMode.Open, System.IO.FileAccess.Read);
                if (stream == null) return;
                xmlReader = System.Xml.XmlReader.Create(stream);
                if (xmlReader == null) return;

                // Parse the XML document.  ReadString is used to 
                // read the text content of the elements.
                xmlReader.Read();
                if (xmlReader.IsStartElement("XYTraceData"))
                {
                    xmlReader.ReadStartElement();

                    //string traceName = "HighThreshold";
                    bool found = false;

                    xmlReader.ReadToNextSibling("Trace");
                    while (!found && xmlReader.IsStartElement("Trace"))
                    {
                        string name = xmlReader.GetAttribute("Name");

                        if (name == traceName)
                        {
                            found = true;
                            xmlReader.ReadStartElement();
                            xmlReader.ReadToNextSibling("Point");
                            while (xmlReader.IsStartElement("Point"))
                            {
                                string x_string_value;
                                string y_string_value;

                                x_string_value = xmlReader.GetAttribute("X");
                                y_string_value = xmlReader.GetAttribute("Y");

                                float x_value;
                                float y_value;
                                if (Single.TryParse(x_string_value, out x_value) && Single.TryParse(y_string_value, out y_value))
                                {
                                    data.Enqueue(new PointF(x_value, y_value));
                                }

                                xmlReader.ReadToNextSibling("Point");
                            }

                            xmlReader.ReadEndElement();
                        }

                        xmlReader.ReadToNextSibling("Trace");
                    }

                    //xmlReader.ReadEndElement();
                }
                else if (xmlReader.IsStartElement("Workbook"))
                {
                    xmlReader.ReadStartElement();

                    bool found = false;

                    xmlReader.ReadToNextSibling("Worksheet");
                    while (!found && xmlReader.IsStartElement("Worksheet"))
                    {
                        string name = xmlReader.GetAttribute("Name", "urn:schemas-microsoft-com:office:spreadsheet");

                        if (name == traceName)
                        {
                            found = true;
                            xmlReader.ReadStartElement();
                            if (!xmlReader.IsStartElement("Table")) xmlReader.ReadToNextSibling("Table");
                            while (xmlReader.IsStartElement("Table"))
                            {
                                xmlReader.ReadStartElement();
                                if (!xmlReader.IsStartElement("Row")) xmlReader.ReadToNextSibling("Row");
                                while (xmlReader.IsStartElement("Row"))
                                {
                                    xmlReader.ReadStartElement();
                                    if (!xmlReader.IsStartElement("Cell")) xmlReader.ReadToNextSibling("Cell");

                                    int column = 0;
                                    float x_value = 0;
                                    float y_value;

                                    while (xmlReader.IsStartElement("Cell"))
                                    {
                                        xmlReader.ReadStartElement();
                                        if (!xmlReader.IsStartElement("Data")) xmlReader.ReadToNextSibling("Data");

                                        if (xmlReader.IsStartElement("Data"))
                                        {
                                            float value = xmlReader.ReadElementContentAsFloat ();

                                            if (column == 0) x_value = value;
                                            else if (column == 1)
                                            {
                                                y_value = value;

                                                data.Enqueue(new PointF(x_value, y_value));
                                            }

                                            xmlReader.ReadEndElement ();
                                        }

                                        column++;
                                        xmlReader.ReadToNextSibling("Cell");
                                    }
                                    xmlReader.ReadToNextSibling("Row");
                                }
                                //string x_string_value;
                                //string y_string_value;

                                //x_string_value = xmlReader.GetAttribute("X");
                                //y_string_value = xmlReader.GetAttribute("Y");

                                //float x_value;
                                //float y_value;
                                //if (Single.TryParse(x_string_value, out x_value) && Single.TryParse(y_string_value, out y_value))
                                //{
                                //    data.Enqueue(new PointF(x_value, y_value));
                                //}

                                xmlReader.ReadToNextSibling("Table");
                            }

                            xmlReader.ReadEndElement();
                        }

                        xmlReader.ReadToNextSibling("Worksheet");
                    }
                }

                xmlReader.Close();
                stream.Close();
                stream.Dispose();

                pointData = new PointF[data.Count];
                for (int count = 0; count < pointData.Length; count++)
                {
                    pointData[count] = data.Dequeue();
                }
            }
            catch (System.IO.IOException)
            {
                // File is not valid, but it may be one day so suppress the exception.
            }

            CalculatePoints();
        }

        private void CalculatePoints()
        {
            CalculatePoints(xScale, yScale, xStart, xEnd, yStart, yEnd);
        }
        
        private Scale xScale;
        private Scale yScale;
        private int xStart;
        private int xEnd;
        private int yStart;
        private int yEnd;

        private void CalculatePoints(Scale xScale, Scale yScale, int xStart, int xEnd, int yStart, int yEnd)
        {
            lock (this)
            {
                Point[] temp_point;

                this.xScale = xScale;
                this.yScale = yScale;
                this.xStart = xStart;
                this.xEnd = xEnd;
                this.yStart = yStart;
                this.yEnd = yEnd;

                if (pointData != null && xScale != null && yScale != null)
                {
                    double x1 = xScale.Minimum;
                    double y1 = yScale.Minimum;
                    double scaleX = (xEnd - xStart) / (xScale.Maximum - xScale.Minimum);
                    double scaleY = (yStart - yEnd) / (yScale.Maximum - yScale.Minimum);

                    int length = pointData.Length;
                    int point_index = 0;
                    temp_point = new Point[length];
                    for (int index = 0; index < length; index++)
                    {
                        temp_point[point_index].X = xStart + (int)((pointData[index].X - x1) * scaleX);
                        temp_point[point_index].Y = yStart - (int)((pointData[index].Y - y1) * scaleY);
                        if (point_index == 0 || temp_point[point_index].X != temp_point[point_index - 1].X || temp_point[point_index].Y != temp_point[point_index - 1].Y)
                        {
                            point_index++;
                        }
                    }
                    if (temp_point.Length != point_index)
                    {
                        Point[] new_point = new Point[point_index];
                        for (int index = 0; index < point_index; index++)
                        {
                            new_point[index] = temp_point[index];
                        }
                        temp_point = new_point;
                    }
                    point = temp_point;
                }
                else
                {
                    point = new Point[0];
                }
            }
        }

