        /// <summary>
        /// Sets the array of points from which the trace is drawn.
        /// </summary>
        /// <param name="xPoints">Array of Double giving the X values of each data point.</param>
        /// <param name="yPoints">Array of Double giving the Y values of each data point.</param>
        public void SetDataPoints(double[] xPoints, double[] yPoints)
        {
            if (xPoints == null) throw new System.ArgumentNullException("xPoints");
            if (yPoints == null) throw new System.ArgumentNullException("yPoints");
            if (xPoints.Length != yPoints.Length) throw new System.ArgumentException("Array lengths must be equal");

            PointF [] points = new PointF[xPoints.Length];

            for (int index = 0 ; index < points.Length; index++)
            {
                points[index].X = (float)xPoints[index];
                points[index].Y = (float)yPoints[index];
            }

            SetDataPoints (points) ;
        }

        /// <summary>
        /// Sets the array of points from which the trace is drawn.
        /// </summary>
        /// <param name="points">Array of PointF giving the X and Y values of each data point.</param>
        public void SetDataPoints(PointF[] points)
        {
            lock (this)
            {
                if (points == null) throw new System.ArgumentNullException("points");

                pointData = points;

                CalculatePoints();
            }

            OnDisplayUpdate(DisplayUpdateMode.Redraw);
        }
