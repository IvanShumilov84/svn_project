        /// <summary>
        /// Given an angle in a rectangle, returns the equivalent angle for a square.
        /// Used by input objects with circular scales
        /// </summary>
        /// <param name="inAngle">Angle in DisplayRectangle</param>
        /// <returns>Equivalent angle in a square</returns>
        protected double UnscaleAngle(double inAngle)
        {
            double outAngle;
            double fraction;

            fraction = Math.Tan(inAngle * Math.PI / 180) * DisplayRectangle.Height / DisplayRectangle.Width;
            outAngle = Math.Atan(fraction) * 180 / Math.PI;
            //period of Tan is 180 deg, so may need to manually offset it
            if (outAngle < 0) outAngle += 180;
            if (inAngle > 180) outAngle += 180;

            return outAngle;
        }
