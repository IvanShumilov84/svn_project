        /// <summary>
        /// Calculates a GraphicsPath that fits the given shape inside the given Rectangle
        /// </summary>
        /// <param name="Rect">Rectangle in which to calculate path</param>
        /// <param name="Shape">Shape of path to calculate</param>
        /// <returns>Calculated GraphicsPath</returns>
        protected Path CalculateShapePath(Rect rect, Shapes shape)
        {
           Path path = new Path();
           GeometryGroup geometryGroup = new GeometryGroup();
            if (Shape == Shapes.Ellipse)
            {
                //ft path.AddEllipse(Rect);
                EllipseGeometry ellipse = new EllipseGeometry();
                ellipse.Center = new Point(rect.X,rect.Y);
                ellipse.RadiusX = cornerRadius;
                ellipse.RadiusY = cornerRadius;
                geometryGroup.Children.Add(ellipse);
            }
            else
            {
                int d = 2 * cornerRadius;

                if (d > (rect.Width / 2))
                {
                    d = (int)rect.Width / 2;
                }
                if (d > (rect.Height / 2))
                {
                    d = (int)rect.Height / 2;
                }

                if (d < 1)
                {
                    //too small to make a rounded rect - use the whole rect
                    //ft path.AddRectangle(Rect);
                    RectangleGeometry rectangleGeometry = new RectangleGeometry();
                   
                    rectangleGeometry.Rect = rect;
                    geometryGroup.Children.Add(rectangleGeometry);
                    path.Data = geometryGroup;
                    return path;
                }

                PathFigure pathFigure = new PathFigure();
                pathFigure.StartPoint = new Point(0, 0);

                PathSegmentCollection pathSegments = new PathSegmentCollection();//ft nouveau
                 
                //ft path.AddArc(rect.Left, rect.Top, d, d, 180, 90);
                ArcSegment arcSegment = new ArcSegment(new Point(rect.Left, rect.Top) ,new Size(d,d), 180,false, SweepDirection.Clockwise, false);
                pathSegments.Add(arcSegment);
                
                //ft path.AddLine(rect.Left + cornerRadius, rect.Top, rect.Right - cornerRadius, rect.Top);
                LineSegment lineSegment = new LineSegment(new Point(rect.Left + cornerRadius, rect.Right - cornerRadius), false);
                pathSegments.Add(lineSegment);
                
                //ft path.AddArc(rect.Right - d, rect.Top, d, d, 270, 90);
                arcSegment = new ArcSegment(new Point(rect.Right-d, rect.Top), new Size(d, d), 270, false, SweepDirection.Clockwise, false);
                pathSegments.Add(arcSegment);

                //ft path.AddLine(rect.Right, rect.Top + cornerRadius, rect.Right, rect.Bottom - cornerRadius);
                lineSegment = new LineSegment(new Point(rect.Right , rect.Top + cornerRadius), false);
                pathSegments.Add(lineSegment);


                //ft path.AddArc(rect.Right - d, rect.Bottom - d, d, d, 0, 90);
                arcSegment = new ArcSegment(new Point(rect.Right - d, rect.Bottom -d ), new Size(d, d), 0, false, SweepDirection.Clockwise, false);
                pathSegments.Add(arcSegment);

                //ft path.AddLine(rect.Right - cornerRadius, rect.Bottom, rect.Left + cornerRadius, rect.Bottom);
                lineSegment = new LineSegment(new Point(rect.Right - cornerRadius, rect.Bottom + cornerRadius),true);
                pathSegments.Add(lineSegment);

                //ft path.AddArc(rect.Left, rect.Bottom - d, d, d, 90, 90);
                arcSegment = new ArcSegment(new Point(rect.Left - d, rect.Bottom - d), new Size(d, d),90, false, SweepDirection.Clockwise, false);
                 pathSegments.Add(arcSegment);

                //ft path.AddLine(rect.Left, rect.Bottom - cornerRadius, rect.Left, rect.Top + cornerRadius);
                lineSegment = new LineSegment(new Point(rect.Left , rect.Bottom - cornerRadius), true);
                pathSegments.Add(lineSegment);

                pathFigure.Segments = pathSegments;

                PathFigureCollection pathFigureCollection = new PathFigureCollection();
                pathFigureCollection.Add(pathFigure);

                PathGeometry pathGeometry = new PathGeometry();
                pathGeometry.Figures = pathFigureCollection;

                
                path.Stroke = Brushes.Black;
                path.StrokeThickness = 1;
                path.Data = pathGeometry;

            }
            //path.Data = geometryGroup;
            return path;
        }
        public static GeometryDrawing GetArc(Rect rect, Angle start, Angle sweep)
        {
            GeometryDrawing ret = new GeometryDrawing();
            StreamGeometry geo = new StreamGeometry();

            SweepDirection sweepDir = sweep.Degrees < 0 ? SweepDirection.Counterclockwise : SweepDirection.Clockwise;
            bool isLargeArc = Math.Abs(sweep.Degrees) > 180;

            double cx = rect.Width / 2;
            double cy = rect.Height / 2;

            double x1 = rect.X + cx + (Math.Cos(start.Radians) * cx);
            double y1 = rect.Y + cy + (Math.Sin(start.Radians) * cy);

            double x2 = rect.X + cx + (Math.Cos(start.Radians + sweep.Radians) * cx);
            double y2 = rect.Y + cy + (Math.Sin(start.Radians + sweep.Radians) * cy);


            using (StreamGeometryContext ctx = geo.Open())
            {
                ctx.BeginFigure(new Point(x1, y1), false, false);
                ctx.ArcTo(new Point(x2, y2), new Size(cx, cy), 0, isLargeArc, sweepDir, true, false);
            }

            ret.Geometry = geo;
            return ret;
        }
        public class Angle
        {
            private static double _GradToRad = 180d / Math.PI;

            int _degrees;
            double _rad;

            public double Radians
            {
                get { return _rad; }
            }

            public int Degrees
            {
                get { return _degrees; }
            }

            public Angle(int degrees)
            {
                _degrees = degrees;
                _rad = (degrees * 1.0) / _GradToRad;
            }

        }

