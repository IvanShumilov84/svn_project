		/// <summary>
		/// Gets or Sets whether the rate at which the Control redraws
		/// </summary>
		[Category("Control")]
		[DefaultValue(UpdateSpeeds.Fast)]
		[Description("Gets or Sets the rate at which the Control redraws")]
		public virtual KineticaRT.Controls.UpdateSpeeds UpdateSpeed
		{
			get
			{
				return updateSpeed ;
			}
			set
			{
				if (updateSpeed != value)
				{
                    lock (queueLock)
					{
						updateSpeed = value ;
						if (inQueue)
						{
							pool.UpdateEvent -= hdlr ;
							inQueue = false ;
						}
                        pool = (updateSpeed == KineticaRT.Controls.UpdateSpeeds.Fast) ? fastPool : slowPool;
						AddToQueue(false) ;
					}
					OnPropertyChanged("UpdateSpeed") ;
				}
			}
		}

